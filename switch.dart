void main() {
  int day=3;
  switch (day){
    case 1:
      print("Sunday");
      break;
    case 2:
      print ("Monday");
      break;
    case 3:
      print("Tuesday");
      break;
    case 4:
      print("Wednesday");
      break;
      case 5:
      print("Thursday");
      break;
    default:
      print("Invalid day");
  }
    
  }